/** An emblem on a square [viewport], its path moved by [dx], [dy] (to centre a narrower one). */
private fun emblem(
    name: String,
    viewport: Float,
    pathData: String,
    dx: Float = 0f,
    dy: Float = 0f,
    fillType: PathFillType = PathFillType.NonZero
): ImageVector =
    ImageVector.Builder(name = name, defaultWidth = 24.dp, defaultHeight = 24.dp, viewportWidth = viewport, viewportHeight = viewport)
        .addGroup(translationX = dx, translationY = dy)
        .addPath(pathData = addPathNodes(pathData), fill = SolidColor(Color.Black), pathFillType = fillType)
        .clearGroup()
        .build()

